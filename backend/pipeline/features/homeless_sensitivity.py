"""Sensitivity check for the modelled homeless estimates.

Re-runs the allocation with an alternative weight (tract population, ACS 2020-2024) and
compares it with the main estimate (severely burdened ELI renters, CHAS): overlap of the
top-N tracts and towns, Spearman rank correlation, and the share of people that would move
between tracts. Writes reports/homeless_sensitivity.md and reports/homeless_sensitivity.json.

Run: uv run python -m pipeline.features.homeless_sensitivity
"""

from __future__ import annotations

import json
import logging

import pandas as pd

from pipeline.features.homeless_estimate import (
    FALLBACK_METRIC,
    WEIGHT_METRIC,
    allocate,
    latest_pit,
)
from pipeline.paths import PROCESSED_DIR, REPORTS_DIR

log = logging.getLogger("pipeline.features.homeless_sensitivity")

TOP_N = 20


def compare(main: pd.Series, alt: pd.Series, top_n: int = TOP_N) -> dict[str, float | int]:
    """main/alt: estimates indexed by area id (same index)."""
    alt = alt.reindex(main.index)
    top_main = set(main.nlargest(top_n).index)
    top_alt = set(alt.nlargest(top_n).index)
    total = float(main.sum())
    return {
        "areas": int(len(main)),
        "top_n": top_n,
        "top_n_overlap": len(top_main & top_alt),
        "top_n_overlap_share": round(len(top_main & top_alt) / top_n, 3),
        "spearman": round(float(main.rank().corr(alt.rank())), 3),
        # half the absolute difference = people allocated to a different area
        "share_reallocated": round(float((main - alt).abs().sum() / 2 / total), 3)
        if total
        else 0.0,
    }


def _town_totals(est: pd.Series, tm: pd.DataFrame) -> pd.Series:
    w = tm[tm.housing_share > 0]
    return (w.tract_geoid.map(est) * w.housing_share).groupby(w.municipality_geoid).sum()


def run() -> dict:
    from app.core.database import get_session_factory
    from app.dao.metric_dao import MetricDao

    tracts = pd.read_parquet(PROCESSED_DIR / "tracts.parquet")
    towns = pd.read_parquet(PROCESSED_DIR / "municipalities.parquet").set_index("geoid").name
    chas = pd.read_parquet(PROCESSED_DIR / "metrics_chas.parquet")
    acs = pd.read_parquet(PROCESSED_DIR / "metrics_acs.parquet")
    w_main = chas[chas.metric == WEIGHT_METRIC].set_index("tract_geoid").value
    pop = acs[acs.metric == FALLBACK_METRIC].set_index("tract_geoid").value
    pit = latest_pit(pd.read_parquet(PROCESSED_DIR / "homelessness_counts.parquet"))
    year = int(pit.year.iloc[0])
    main = allocate(tracts, w_main, pop, pit).set_index("geoid").total
    alt = allocate(tracts, pop, pop, pit).set_index("geoid").total

    with get_session_factory()() as session:
        rows = MetricDao(session).tract_municipality_weights()
    tm = pd.DataFrame(rows, columns=["tract_geoid", "municipality_geoid", "housing_share"])
    if tm.housing_share.isna().any():
        raise ValueError(
            "tract_municipalities.housing_share missing: run pipeline.features.aggregate"
        )
    town_main, town_alt = _town_totals(main, tm), _town_totals(alt, tm)

    result = {
        "pit_year": year,
        "main_weight": f"{WEIGHT_METRIC} (HUD CHAS 2018-2022)",
        "alternative_weight": f"{FALLBACK_METRIC} (ACS 2020-2024)",
        "tracts": compare(main, alt),
        "municipalities": compare(town_main, town_alt),
        "municipalities_top10": compare(town_main, town_alt, 10),
    }
    names = tracts.set_index("geoid").municipality_geoid.map(towns)
    top = pd.DataFrame({"main": main, "alt": alt})
    top["town"] = names
    top_tracts = top.nlargest(TOP_N, "main")
    top_towns = pd.DataFrame({"main": town_main, "alt": town_alt}).nlargest(TOP_N, "main")
    top_towns.index = top_towns.index.map(towns)

    (REPORTS_DIR / "homeless_sensitivity.json").write_text(json.dumps(result, indent=2) + "\n")
    (REPORTS_DIR / "homeless_sensitivity.md").write_text(_markdown(result, top_tracts, top_towns))
    log.info("sensitivity: %s", result)
    return result


def _markdown(r: dict, top_tracts: pd.DataFrame, top_towns: pd.DataFrame) -> str:
    t, m = r["tracts"], r["municipalities"]
    lines = [
        "# Sensitivity of the modelled homeless estimates (ESTIMATES)",
        "",
        "Generated by `pipeline.features.homeless_sensitivity`. Both allocations distribute the "
        f"same official HUD PIT {r['pit_year']} CoC counts; only the within-CoC weight differs.",
        "",
        f"- Main weight: {r['main_weight']}",
        f"- Alternative weight: {r['alternative_weight']}",
        "",
        "| Level | Areas | Top-20 overlap | Spearman rank corr. | People allocated elsewhere |",
        "|---|---|---|---|---|",
        f"| Tract | {t['areas']} | {t['top_n_overlap']}/20 | {t['spearman']} | "
        f"{100 * t['share_reallocated']:.1f}% |",
        f"| Town | {m['areas']} | {m['top_n_overlap']}/20 | {m['spearman']} | "
        f"{100 * m['share_reallocated']:.1f}% |",
        "",
        f"Top-10 towns overlap: {r['municipalities_top10']['top_n_overlap']}/10.",
        "",
        "## Top 20 tracts by main estimate",
        "",
        "| Tract | Town | Estimate (main) | Estimate (population share) |",
        "|---|---|---|---|",
    ]
    for geoid, row in top_tracts.iterrows():
        lines.append(f"| {geoid} | {row.town} | {row.main:.1f} | {row.alt:.1f} |")
    lines += [
        "",
        "## Top 20 towns by main estimate",
        "",
        "| Town | Estimate (main) | Estimate (population share) |",
        "|---|---|---|",
    ]
    for name, row in top_towns.iterrows():
        lines.append(f"| {name} | {row.main:.1f} | {row.alt:.1f} |")
    lines += [
        "",
        "Estimates are modelled shares of CoC totals, not counts of people in an area.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    run()
