"""Load cleaned tables (data/processed/*.parquet) into Postgres via LoadService/BulkDao.

Idempotent: natural-key tables are upserted; point tables nothing references are replaced.
Writes reports/load_summary.md with row counts and the dropped-row log.

Run: uv run python -m pipeline.load
"""

from __future__ import annotations

import json
import logging
import sys

import pandas as pd

from app.core.database import get_session_factory
from app.dao.bulk_dao import BulkDao
from app.dao.data_source_dao import DataSourceDao
from app.models import (
    BostonNeighbourhood,
    Coc,
    CocBedCount,
    CocMunicipality,
    County,
    HomelessnessCount,
    Municipality,
    NeighbourhoodTract,
    Shelter,
    SubsidisedHousing,
    Tract,
    TractMetric,
    TractMunicipality,
    TransitStop,
    ZipTract,
)
from app.services.load_service import LoadService
from pipeline.drops import all_drops
from pipeline.paths import PROCESSED_DIR, REPORTS_DIR

log = logging.getLogger("pipeline.load")


def _read(name: str) -> pd.DataFrame:
    return pd.read_parquet(PROCESSED_DIR / f"{name}.parquet")


def _records(df: pd.DataFrame) -> list[dict]:
    df = df.astype(object).where(df.notna(), None)
    return df.to_dict("records")


def _geo(df: pd.DataFrame, source_key: str) -> list[dict]:
    df = df.copy()
    df["boundary"] = df.boundary.apply(json.loads)
    df["source_key"] = source_key
    return _records(df)


METRIC_FILES = ["metrics_acs", "metrics_context", "metrics_chas", "metrics_homeless"]


def load_all(service: LoadService) -> dict[str, int]:
    counts: dict[str, int] = {}
    counts["counties"] = service.upsert(
        County, _geo(_read("counties"), "tiger_counties"), ["geoid"]
    )
    counts["municipalities"] = service.upsert(
        Municipality, _geo(_read("municipalities"), "tiger_cousub"), ["geoid"]
    )
    counts["cocs"] = service.upsert(Coc, _geo(_read("cocs"), "hud_coc_boundaries"), ["coc_number"])
    counts["coc_municipalities"] = service.upsert(
        CocMunicipality,
        _records(_read("coc_municipalities")),
        ["coc_number", "municipality_geoid"],
    )
    hoods = _read("boston_neighbourhoods").rename(columns={"neighbourhood_id": "id"})
    counts["boston_neighbourhoods"] = service.upsert(
        BostonNeighbourhood, _geo(hoods, "boston_neighbourhoods"), ["id"]
    )
    counts["tracts"] = service.upsert(Tract, _geo(_read("tracts"), "tiger_tracts"), ["geoid"])
    counts["tract_municipalities"] = service.upsert(
        TractMunicipality,
        _records(_read("tract_municipalities")),
        ["tract_geoid", "municipality_geoid"],
    )
    counts["neighbourhood_tracts"] = service.upsert(
        NeighbourhoodTract,
        _records(_read("neighbourhood_tracts")),
        ["neighbourhood_id", "tract_geoid"],
    )
    zt = _read("zip_tracts").assign(source_key="census_zcta_tract")
    counts["zip_tracts"] = service.replace(ZipTract, _records(zt))

    metrics = pd.concat([_read(f) for f in METRIC_FILES], ignore_index=True)
    counts["tract_metrics"] = service.replace_metrics(TractMetric, _records(metrics))

    pit = _read("homelessness_counts").assign(source_key="hud_pit")
    counts["homelessness_counts"] = service.upsert(
        HomelessnessCount, _records(pit), ["coc_number", "year"]
    )
    hic = _read("coc_bed_counts").assign(source_key="hud_hic")
    counts["coc_bed_counts"] = service.upsert(CocBedCount, _records(hic), ["coc_number", "year"])
    shelters = _read("shelters").assign(source_key="osm_shelters")
    counts["shelters"] = service.replace(Shelter, _records(shelters))
    counts["subsidised_housing"] = service.replace(
        SubsidisedHousing, _records(_read("subsidised_housing"))
    )
    counts["transit_stops"] = service.replace(TransitStop, _records(_read("transit_stops")))
    return counts


def write_summary(counts: dict[str, int]) -> None:
    lines = [
        "# Load summary",
        "",
        "Generated by `uv run --project backend python -m pipeline.load`.",
        "",
        "| Table | Rows loaded |",
        "|---|---|",
        *[f"| {t} | {n:,} |" for t, n in counts.items()],
        "",
        "## Rows dropped during cleaning",
        "",
        "| Step | Reason | Rows |",
        "|---|---|---|",
    ]
    for step, reasons in all_drops().items():
        lines += [f"| {step} | {reason} | {n:,} |" for reason, n in reasons.items()]
    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "load_summary.md").write_text("\n".join(lines) + "\n")


def main() -> int:
    with get_session_factory()() as session:
        service = LoadService(BulkDao(session), DataSourceDao(session))
        counts = load_all(service)
    for t, n in counts.items():
        log.info("%s: %d", t, n)
    write_summary(counts)
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    sys.exit(main())
