"""Need Index sensitivity: recompute the index with 3 alternative weightings and report how
stable the statewide top 20 tracts are.

Run: uv run python -m pipeline.index.sensitivity
"""

from __future__ import annotations

import json
import logging

import pandas as pd

from pipeline.index.need_index import EQUAL_WEIGHTS, compute, index_from_scores
from pipeline.paths import PROCESSED_DIR, REPORTS_DIR

log = logging.getLogger("pipeline.index.sensitivity")

TOP_N = 20

ALTERNATIVES: dict[str, tuple[str, dict[str, float]]] = {
    "affordability_heavy": (
        "affordable gap per ELI renter and severe rent burden weighted x2",
        {
            **EQUAL_WEIGHTS,
            "affordable_gap_per_eli_renter": 2.0,
            "severe_rent_burden_share": 2.0,
        },
    ),
    "homelessness_heavy": (
        "homeless estimate per 1,000 and eviction filing rate weighted x2",
        {**EQUAL_WEIGHTS, "homeless_estimate_per_1000": 2.0, "eviction_filing_rate": 2.0},
    ),
    "dense_components_only": (
        "rent growth and eviction rate dropped (the two components missing for many tracts)",
        {**EQUAL_WEIGHTS, "zori_growth_5yr": 0.0, "eviction_filing_rate": 0.0},
    ),
}


def stability(main: pd.Series, alt: pd.Series, top_n: int = TOP_N) -> dict[str, float | int]:
    both = pd.DataFrame({"main": main, "alt": alt}).dropna()
    top_main = both.main.nlargest(top_n).index
    top_alt = set(both.alt.nlargest(top_n).index)
    rank_alt = both.alt.rank(ascending=False, method="min")
    return {
        "tracts_compared": int(len(both)),
        "top_n": top_n,
        "top_n_overlap": len(set(top_main) & top_alt),
        "spearman": round(float(both.main.rank().corr(both.alt.rank())), 3),
        "median_alt_rank_of_main_top_n": float(rank_alt[top_main].median()),
        "worst_alt_rank_of_main_top_n": int(rank_alt[top_main].max()),
    }


def run() -> dict:
    _, sc, main_idx = compute()
    tracts = pd.read_parquet(PROCESSED_DIR / "tracts.parquet").set_index("geoid")
    towns = pd.read_parquet(PROCESSED_DIR / "municipalities.parquet").set_index("geoid").name
    main = main_idx.need_index
    results: dict = {"top_n": TOP_N, "alternatives": {}}
    table = pd.DataFrame({"equal": main})
    for name, (desc, weights) in ALTERNATIVES.items():
        alt = index_from_scores(sc, weights).need_index
        table[name] = alt
        results["alternatives"][name] = {"description": desc, **stability(main, alt)}
    top = table.nlargest(TOP_N, "equal")
    ranks = table.rank(ascending=False, method="min")
    (REPORTS_DIR / "need_index_sensitivity.json").write_text(json.dumps(results, indent=2) + "\n")
    lines = [
        "# Need Index sensitivity to the weights",
        "",
        "Generated by `pipeline.index.sensitivity`. Main index: equal weights over the 8 "
        "components. Each alternative recomputes the index from the same 0-1 scores.",
        "",
        "| Alternative | Weights | Top-20 overlap | Spearman | Median / worst new rank of "
        "the main top 20 |",
        "|---|---|---|---|---|",
    ]
    for name, r in results["alternatives"].items():
        lines.append(
            f"| {name} | {r['description']} | {r['top_n_overlap']}/{TOP_N} | {r['spearman']} | "
            f"{r['median_alt_rank_of_main_top_n']:.0f} / {r['worst_alt_rank_of_main_top_n']} |"
        )
    lines += [
        "",
        "## Main top 20 tracts and their rank under each alternative",
        "",
        "| Rank | Tract | Town | Index | " + " | ".join(ALTERNATIVES) + " |",
        "|---|---|---|---|" + "---|" * len(ALTERNATIVES),
    ]
    for i, (geoid, row) in enumerate(top.iterrows(), start=1):
        town = towns.get(tracts.municipality_geoid.get(geoid), "")
        alt_ranks = " | ".join(f"{int(ranks.loc[geoid, a])}" for a in ALTERNATIVES)
        lines.append(f"| {i} | {geoid} | {town} | {row.equal:.1f} | {alt_ranks} |")
    lines.append("")
    (REPORTS_DIR / "need_index_sensitivity.md").write_text("\n".join(lines))
    log.info("need index sensitivity: %s", results)
    return results


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    run()
